def detect_language(text: str) -> str:
    """Простое определение языка: ky, если есть кыргызские маркеры/слова."""
    if not text:
        return "ru"
    lowered = text.lower()
    if any(ch in _KY_MARKERS for ch in lowered):
        return "ky"
    words = set(re.findall(r"\w+", lowered))
    if words & _KY_WORDS:
        return "ky"
    return "ru"


def t(key: str, lang: str) -> str:
    """Возвращает перевод строки. Fallback — русский."""
    table = STRINGS.get(lang) or STRINGS["ru"]
    return table.get(key) or STRINGS["ru"].get(key, key)
